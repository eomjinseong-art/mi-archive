import type { LicensedImage } from "./types";

const COMMONS = "Wikimedia Commons";
const PD_MARK = "https://creativecommons.org/publicdomain/mark/1.0/";

function img(
  file: string,
  width: number,
  height: number,
  alt: string,
  author: string,
  license: string,
  licenseUrl: string,
  sourceUrl: string,
): LicensedImage {
  return {
    src: `/images/licensed/${file}`,
    width,
    height,
    alt,
    author,
    license,
    licenseUrl: licenseUrl || PD_MARK,
    sourceUrl,
    sourceLabel: COMMONS,
  };
}

/** User-licensed Getty portrait. Credit text only — no Commons URLs. */
function gettyPortrait(
  file: string,
  width: number,
  height: number,
  alt: string,
  objectPosition?: string,
): LicensedImage {
  return {
    src: `/images/directors/${file}`,
    width,
    height,
    alt,
    author: "Getty Images",
    license: "사용자 라이선스",
    licenseUrl: "",
    sourceUrl: "",
    sourceLabel: "",
    objectPosition,
  };
}

