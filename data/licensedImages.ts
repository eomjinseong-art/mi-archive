/**
 * Commons portraits that still read close to the film-era face.
 * Later red-carpet / convention shots of the same actresses stay in
 * `bondGirlImages` for credit, but are not used as heroes.
 */
const BOND_GIRL_FILM_ERA_HERO = new Set([
  "tatiana-romanova",
  "tracy-di-vicenzo",
  "vesper-lynd",
  "madeleine-swann",
]);

export function bondGirlHeroImage(slug: string): LicensedImage | undefined {
  const image = bondGirlImages[slug];
  if (image && BOND_GIRL_FILM_ERA_HERO.has(slug)) return image;
  return undefined;
}

